#!/usr/bin/env python3
"""Generate the end-game "HNM" roster: very strong named mobs on ~24 hour respawns.

Writes apps2/mud/hnm_gen.go and merges drop tables into data/mob_drops.json (rows keyed by the
HNM's character name, so they are editable in IDUNA's mob-drops page). Every dropped item must be a
row of data/items.json; the script asserts it.

Run from the repo root:  python3 scripts/gen_hnm.py && gofmt -w apps2/mud/hnm_gen.go
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def P(*a): return os.path.join(ROOT, *a)
def slug(n): return n.lower().replace(" ", "-")
def gostr(s): return json.dumps(s, ensure_ascii=False)

# id, name, zone, level, hp, damage, xp, lair blurb, [(item, chance)]
